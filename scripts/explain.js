// Executes docs/sql-examples.sql against a TEMPORARY synthetic database, verifies each section behaves as annotated,
// and writes real EXPLAIN QUERY PLAN output to docs/query-plans.md. It never touches your development database.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Db, driverName } from '../server/src/lib/db.js';
import { migrate } from '../server/src/db/migrate.js';
import { ROOT } from '../server/src/config.js';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'luna-explain-'));
const db = new Db(path.join(dir, 'explain.db'));
migrate(db);

// ---- synthetic data (temp DB only) ----
const N_USERS = 60, N_LOST = 3000, N_FOUND = 3000;
let seed = 42;
const rnd = (n) => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed % n; };
const nCat = db.get('SELECT COUNT(*) n FROM categories').n, nLoc = db.get('SELECT COUNT(*) n FROM campus_locations').n;
const iso = (daysAgo) => new Date(Date.now() - daysAgo * 86400000).toISOString();
const day = (daysAgo) => iso(daysAgo).slice(0, 10);
db.tx(() => {
  for (let i = 1; i <= N_USERS; i++) db.run("INSERT INTO users (email, password_hash, full_name, role) VALUES (?, 'x', ?, ?)", `u${i}@x.edu`, `User ${i}`, i <= 3 ? 'staff' : 'student');
  const words = ['phone', 'wallet', 'keys', 'bag', 'bottle', 'laptop', 'umbrella', 'book', 'watch', 'card'];
  const lostStatus = ['open', 'open', 'open', 'resolved', 'withdrawn'];
  const foundStatus = ['reported', 'stored', 'stored', 'under_review', 'returned', 'claim_pending'];
  for (let i = 0; i < N_LOST; i++) {
    const ago = rnd(400);
    db.run('INSERT INTO lost_reports (user_id, title, category_id, description, last_seen_date, location_id, status, created_at) VALUES (?,?,?,?,?,?,?,?)',
      4 + rnd(N_USERS - 3), `${words[rnd(10)]} lost ${i}`, 1 + rnd(nCat), `A ${words[rnd(10)]} that was lost on campus, number ${i}`, day(ago), 1 + rnd(nLoc), lostStatus[rnd(5)], iso(ago));
  }
  for (let i = 0; i < N_FOUND; i++) {
    const ago = rnd(400);
    db.run('INSERT INTO found_reports (user_id, title, category_id, description, found_date, location_id, status, created_at) VALUES (?,?,?,?,?,?,?,?)',
      4 + rnd(N_USERS - 3), `${words[rnd(10)]} found ${i}`, 1 + rnd(nCat), `A ${words[rnd(10)]} that was found on campus, number ${i}`, day(ago), 1 + rnd(nLoc), foundStatus[rnd(6)], iso(ago));
  }
  // claims: some found items get two competing claims; a few approved; handovers for completed ones
  const stored = db.all("SELECT id FROM found_reports WHERE status IN ('stored','claim_pending') LIMIT 400");
  for (const f of stored) {
    const first = 4 + rnd(N_USERS - 3);
    db.run("INSERT INTO claims (found_report_id, claimant_id, explanation, status, created_at) VALUES (?, ?, 'It is mine, it has my initials', 'under_review', ?)", f.id, first, iso(rnd(10)));
    if (rnd(3) === 0) db.run("INSERT INTO claims (found_report_id, claimant_id, explanation, status, created_at) VALUES (?, ?, 'I think this is mine too', 'under_review', ?)", f.id, first === N_USERS ? 4 : first + 1, iso(rnd(10)));
  }
  for (const f of db.all("SELECT id FROM found_reports WHERE status = 'returned' LIMIT 150")) {
    const cid = Number(db.run("INSERT INTO claims (found_report_id, claimant_id, explanation, status) VALUES (?, 5, 'Verified owner explanation text', 'completed')", f.id).lastInsertRowid);
    db.run("INSERT INTO handovers (claim_id, found_report_id, handed_by, recipient_name, handed_at) VALUES (?, ?, 1, 'Owner', ?)", cid, f.id, iso(rnd(30)));
  }
  db.run("INSERT INTO item_photos (found_report_id, stored_name, mime_type, size_bytes, uploaded_by) VALUES (1, '0123456789abcdef0123456789abcdef.png', 'image/png', 10, 1)");
  db.run("INSERT INTO audit_logs (actor_id, action, entity_type, entity_id) VALUES (1, 'demo.action', 'user', 1)");
});
db.exec('ANALYZE');

// ---- parse + run sections ----
const text = fs.readFileSync(path.join(ROOT, 'docs', 'sql-examples.sql'), 'utf8');
const sections = text.split(/^-- ### /m).slice(1).map((s) => {
  const [titleLine, ...rest] = s.split('\n');
  const body = rest.join('\n');
  const meta = {
    explain: /^-- @explain\s*$/m.test(body),
    expectError: (/^-- @expect-error (.+)$/m.exec(body) || [])[1],
    expectRows: (/^-- @expect-rows (\d+)/m.exec(body) || [])[1],
    expectMin: (/^-- @expect-min (\d+)/m.exec(body) || [])[1],
  };
  const sql = body.split('\n').filter((l) => !l.trim().startsWith('--')).join('\n').trim();
  return { title: titleLine.trim(), sql, meta };
});
// split a section into statements on ';' at end of line (no string literal in this file contains ';')
const statements = (sql) => sql.split(/;\s*(?:\n|$)/).map((s) => s.trim()).filter(Boolean);

let failures = 0;
const planDoc = [`# Query plans (generated)\n`, `Generated by \`node scripts/explain.js\` on ${new Date().toISOString().slice(0, 10)} using SQLite driver \`${driverName}\` (SQLite ${db.get('SELECT sqlite_version() v').v}).`,
  `Dataset: synthetic and temporary: ${N_LOST} lost reports, ${N_FOUND} found reports, ${N_USERS} users, ~${db.get('SELECT COUNT(*) n FROM claims').n} claims; \`ANALYZE\` was run. Plans depend on the SQLite version and table statistics, so yours may differ. These are real outputs, not benchmarks (no timings are claimed).\n`];
for (const sec of sections) {
  let outcome = 'ok';
  try {
    const stmts = statements(sec.sql);
    if (sec.meta.expectError) {
      for (const setup of stmts.slice(0, -1)) db.exec(setup); // earlier statements are setup; the LAST one must fail
      for (const st of stmts.slice(-1)) {
        let threw = null;
        try { db.exec(st); } catch (e) { threw = e; }
        if (!threw) throw new Error(`expected an error containing "${sec.meta.expectError}" but statement succeeded`);
        if (!String(threw.message).includes(sec.meta.expectError)) throw new Error(`wrong error: ${threw.message}`);
        outcome = `rejected as expected: ${threw.message}`;
      }
    } else {
      let rows = null; let firstSelect = null;
      for (const st of stmts) {
        if (/^(WITH|SELECT)/i.test(st)) { rows = db.all(st); firstSelect ||= st; }
        else if (/^(BEGIN|COMMIT|ROLLBACK)/i.test(st)) { /* transaction demos manage themselves below */ db.exec(st); }
        else db.exec(st);
      }
      if (sec.meta.expectRows !== undefined && rows.length !== Number(sec.meta.expectRows)) throw new Error(`expected ${sec.meta.expectRows} rows, got ${rows.length}`);
      if (sec.meta.expectMin !== undefined && rows.length < Number(sec.meta.expectMin)) throw new Error(`expected >= ${sec.meta.expectMin} rows, got ${rows.length}`);
      outcome = rows ? `${rows.length} row(s)${rows.length ? `; first: ${JSON.stringify(Object.fromEntries(Object.entries(rows[0]).map(([k, v]) => [k, typeof v === 'string' && v.length > 40 ? v.slice(0, 37) + '...' : v])))}` : ''}` : 'ok';
      if (/rollback/i.test(sec.title)) { const r = rows[0]; if (Object.values(r)[0] !== 0) throw new Error('rollback left data behind'); }
      if (sec.meta.explain) {
        const plan = db.all(`EXPLAIN QUERY PLAN ${firstSelect}`).map((p) => p.detail);
        planDoc.push(`## ${sec.title}\n`, '```sql', firstSelect, '```', '```text', ...plan, '```\n');
      }
    }
  } catch (e) {
    failures++;
    outcome = `FAILED: ${e.message}`;
    try { db.exec('ROLLBACK'); } catch { /* none open */ }
  }
  console.log(`${outcome.startsWith('FAILED') ? 'FAIL' : 'ok  '} ${sec.title}\n       ${outcome}`);
}
fs.writeFileSync(path.join(ROOT, 'docs', 'query-plans.md'), planDoc.join('\n'));
db.close();
fs.rmSync(dir, { recursive: true, force: true });
console.log(`\n${sections.length - failures}/${sections.length} sections behaved as documented. Plans written to docs/query-plans.md`);
process.exit(failures ? 1 : 0);
