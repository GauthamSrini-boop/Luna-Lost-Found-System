// Generates docs/data-dictionary.md (from the live SQLite schema) and docs/api-routes.md (from the route table).
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { Db } from '../server/src/lib/db.js';
import { migrate } from '../server/src/db/migrate.js';
import { defineRoutes } from '../server/src/routes/index.js';
import { ROOT } from '../server/src/config.js';

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'luna-docs-'));
const db = new Db(path.join(tmp, 'docs.db'));
migrate(db);

const tables = db.all("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name != 'schema_migrations' ORDER BY name");
let dd = '# Data dictionary\n\n_Generated by `npm run docs:generate` from the real schema after running all migrations. Do not edit by hand._\n\n';
for (const { name } of tables) {
  dd += `## \`${name}\`\n\n| Column | Type | Null | Default | Key / references |\n|---|---|---|---|---|\n`;
  const fks = Object.fromEntries(db.all(`PRAGMA foreign_key_list(${name})`).map((f) => [f.from, `FK → ${f.table}.${f.to} (on delete ${f.on_delete})`]));
  for (const c of db.all(`PRAGMA table_info(${name})`)) {
    const key = [c.pk ? 'PK' : '', fks[c.name] || ''].filter(Boolean).join('; ');
    dd += `| ${c.name} | ${c.type || ''} | ${c.notnull ? 'NOT NULL' : 'null'} | ${c.dflt_value ?? ''} | ${key} |\n`;
  }
  const sql = db.get('SELECT sql FROM sqlite_master WHERE name = ?', name).sql;
  const checks = [...sql.matchAll(/CHECK\s*\(([^\n]*)\)/gi)].map((m) => m[1].trim());
  if (checks.length) dd += `\n**Constraints:**\n${checks.map((c) => `- \`CHECK (${c.replace(/\|/g, '\\|')})\``).join('\n')}\n`;
  const idx = db.all(`SELECT name, sql FROM sqlite_master WHERE type='index' AND tbl_name=? AND sql IS NOT NULL ORDER BY name`, name);
  if (idx.length) dd += `\n**Indexes:**\n${idx.map((i) => `- \`${i.name}\``).join('\n')}\n`;
  dd += '\n';
}
const triggers = db.all("SELECT name, tbl_name FROM sqlite_master WHERE type='trigger' ORDER BY name");
if (triggers.length) dd += `## Triggers\n\n${triggers.map((t) => `- \`${t.name}\` on \`${t.tbl_name}\``).join('\n')}\n`;

let er = '# Entity-relationship diagram\n\n_Generated by `npm run docs:generate` from the real foreign keys. Do not edit by hand._\n\n```mermaid\nerDiagram\n';
for (const { name } of tables) {
  for (const f of db.all(`PRAGMA foreign_key_list(${name})`)) er += `  ${f.table} ||--o{ ${name} : "${f.from}"\n`;
}
for (const { name } of tables) {
  er += `  ${name} {\n`;
  for (const c of db.all(`PRAGMA table_info(${name})`)) er += `    ${(c.type || 'TEXT').split('(')[0]} ${c.name}${c.pk ? ' PK' : ''}\n`;
  er += '  }\n';
}
er += '```\n\nCardinality is drawn as one-to-many for every foreign key; UNIQUE indexes (e.g. `handovers.found_report_id`) make some of them effectively one-to-one — see the data dictionary.\n';
db.close();

const routes = defineRoutes();
const who = { public: 'Anyone', auth: 'Signed-in user', staff: 'Staff or admin', admin: 'Admin only' };
let api = '# API route table\n\n_Generated by `npm run docs:generate` from the route table used by the server. Do not edit by hand._\n\n'
  + 'All bodies are JSON (photo upload is `multipart/form-data`, field `photo`). Mutating requests (`POST`/`PATCH`/`PUT`/`DELETE`) must send header `X-Requested-With: LUNA` (CSRF defence). Authentication is the HttpOnly cookie `luna_sid`.\n\n'
  + '| Method | Path | Access |\n|---|---|---|\n';
for (const r of routes) api += `| ${r.method} | \`${r.path}\` | ${who[r.access] || r.access} |\n`;
api += `\n${routes.length} routes.\n`;

fs.writeFileSync(path.join(ROOT, 'docs', 'data-dictionary.md'), dd);
fs.writeFileSync(path.join(ROOT, 'docs', 'api-routes.md'), api);
fs.writeFileSync(path.join(ROOT, 'docs', 'er-diagram.md'), er);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`wrote data-dictionary.md (${tables.length} tables) and api-routes.md (${routes.length} routes)`);
